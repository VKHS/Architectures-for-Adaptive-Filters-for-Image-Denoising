"""Write the constant tables of the HLS code from the Python models (the same values as the RTL ROMs).

    python hls/scripts/gen_tables.py      # writes hls/include/afhls/cos1024_q12.inc
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from afarch import frontends as fe                                         # noqa: E402

tab = fe.cos_table(10, 1.0, 12)
hexlines = (REPO / "rtl" / "scenarios" / "cos1024_q12.hex").read_text().splitlines()
hexrom = [int(v, 16) for ln in hexlines if not ln.startswith("//") for v in ln.split()]
assert [int(v) & 0xFFFF for v in tab] == hexrom, "the HLS table must equal the RTL ROM"
out = REPO / "hls" / "include" / "afhls" / "cos1024_q12.inc"
lines = ["// cos(2 pi a / 1024) in Q12, a = 0 .. 1023: generated by hls/scripts/gen_tables.py, equal to",
         "// rtl/scenarios/cos1024_q12.hex."]
for i in range(0, 1024, 16):
    lines.append(", ".join(f"{int(v):5d}" for v in tab[i:i + 16]) + ",")
out.write_text("\n".join(lines) + "\n")
print("wrote", out.relative_to(REPO))
